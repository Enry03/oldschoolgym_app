const { chromium, login, check, shot, BASE, done } = require('./lib.cjs')
const { expect } = require('playwright/test')
const { execSync } = require('child_process')
const sql = (q) => execSync(`psql -h localhost -p 54322 -U postgres -d postgres -Atc "${q}"`, { env: { ...process.env, PGPASSWORD: 'postgres' } }).toString().trim()
;(async () => {
  const browser = await chromium.launch()
  // promemoria automatici (il cron gira ogni ora: qui lo lanciamo a mano)
  sql('select private.run_reminders()')
  const t = await login(browser, 'trainer@e2e.it')
  await check('il trainer entra nel pannello staff', () => expect(t).toHaveURL(/\/staff/))
  await check('Da seguire: scheda di Carlo da 6 settimane', () => expect(t.getByText(/scheda "Forza e massa" da 6 settimane/)).toBeVisible())
  await check('Da seguire: Carlo ha ancora 1 ingresso', () => expect(t.getByText(/ancora 2 ingressi|ancora 1 ingresso/)).toBeVisible())
  await check('Da seguire: il trainer NON vede Cinzia (non è sua)', () => expect(t.getByText('Cinzia Bianchi')).toHaveCount(0))
  await shot(t, 't_dashboard')
  await t.getByRole('button', { name: 'Notifiche' }).click()
  await check('notifiche trainer: record di Carlo, cambio scheda, messaggio', async () => {
    await expect(t.getByText('Record di Carlo Rossi 🏆')).toBeVisible()
    await expect(t.getByText('È ora di cambiare scheda 📋')).toBeVisible()
    await expect(t.getByText('Messaggio da Carlo Rossi')).toBeVisible()
  })
  await t.getByText('Messaggio da Carlo Rossi').click()
  await check('la notifica apre la chat con Carlo', () => expect(t.getByText('Ciao Tino, oggi 85 kg di panca!')).toBeVisible({ timeout: 8000 }))
  await t.getByPlaceholder('Scrivi un messaggio…').fill('Grande Carlo! Settimana prossima cambiamo scheda')
  await t.getByRole('button', { name: 'Invia' }).click()
  await t.waitForTimeout(800)
  await t.getByText('← Indietro').click()
  await check('lista chat staff: letto, ultimo messaggio mio', () => expect(t.getByText(/Tu: Grande Carlo/)).toBeVisible())

  const carlo = sql("select id from public.profiles where email='cliente1@e2e.it'")
  await t.goto(BASE + '/staff/clienti/' + carlo)
  await t.getByRole('button', { name: 'Diario', exact: true }).click()
  await check('Diario del cliente: panca con Record e nota', async () => {
    await expect(t.getByText('Record', { exact: true })).toBeVisible()
    await expect(t.getByText('“Ultima serie dura”')).toBeVisible()
    await expect(t.getByText(/85 kg × 6/)).toBeVisible()
  })
  await shot(t, 't_diario')
  await t.getByRole('button', { name: 'Progressi', exact: true }).click()
  await check('Progressi: record e grafici del cliente', () => expect(t.getByText(/prima 80 kg/)).toBeVisible())
  await check('Progressi: il trainer vede SOLO la foto condivisa', () => expect(t.getByRole('img', { name: /Foto del/ })).toHaveCount(1))
  await check('la foto condivisa si apre', async () => { await t.waitForTimeout(800); const ok = await t.getByRole('img', { name: /Foto del/ }).evaluate((i) => i.complete && i.naturalWidth > 0); if (!ok) throw new Error('non caricata') })
  await check('Traguardi del cliente visibili al trainer', () => expect(t.getByText(/Traguardi \(\d+\/12\)/)).toBeVisible())
  await shot(t, 't_progressi')

  const a = await login(browser, 'admin@e2e.it')
  await check('admin: Da seguire con Cinzia mai venuta da 25 giorni', () => expect(a.getByText(/iscritto da 25 giorni, mai venuto/)).toBeVisible())
  await a.getByRole('button', { name: 'Notifiche' }).click()
  await check('admin: avviso "Da richiamare: Cinzia Bianchi"', () => expect(a.getByText('Da richiamare: Cinzia Bianchi')).toBeVisible())
  await a.goto(BASE + '/staff/impostazioni')
  await check('impostazioni: campo cambio scheda (settimane)', () => expect(a.getByText(/Avviso cambio scheda dopo/)).toBeVisible())
  const inp = a.getByLabel(/Avviso cambio scheda/)
  await inp.fill('8')
  await a.getByRole('button', { name: /Salva/ }).last().click()
  await a.waitForTimeout(1200)
  await check('impostazione salvata nel database (8 settimane)', () => { if (sql('select plan_change_weeks from public.gym_settings') !== '8') throw new Error('non salvata') })
  sql('update public.gym_settings set plan_change_weeks = 6')

  const c2 = await login(browser, 'cliente2@e2e.it')
  await c2.goto(BASE + '/app/notifiche')
  await check('Cinzia riceve "Ci manchi"', () => expect(c2.getByText('Ci manchi, Cinzia! 🥊')).toBeVisible())
  await c2.goto(BASE + '/staff')
  await check('una cliente non entra nel pannello staff', () => expect(c2).not.toHaveURL(/\/staff/))

  const c1 = await login(browser, 'cliente1@e2e.it')
  await c1.goto(BASE + '/app/messaggi')
  await check('Carlo vede 1 messaggio non letto', () => expect(c1.getByLabel('1 non letti')).toBeVisible())
  await c1.goto(BASE + '/app/notifiche')
  await c1.getByText('Messaggio da Tino Trainer').click()
  await check('la notifica porta Carlo alla chat con Tino', () => expect(c1.getByText('Grande Carlo! Settimana prossima cambiamo scheda')).toBeVisible({ timeout: 8000 }))
  await browser.close()
  process.exit(done())
})()
