const { chromium, login, check, shot, BASE, done } = require('./lib.cjs')
const { expect } = require('playwright/test')
;(async () => {
  const browser = await chromium.launch()
  const p = await login(browser, 'cliente1@e2e.it')
  await p.goto(BASE + '/app/allenamento')
  await check('la scheda mostra gli esercizi', () => expect(p.getByText('Panca piana').first()).toBeVisible())
  await p.getByText('Panca piana').first().click()
  await check('nel diario compare il record precedente (80 kg)', () => expect(p.getByText('Record 80 kg')).toBeVisible())
  const kg = p.getByPlaceholder('kg'), reps = p.getByPlaceholder('reps')
  await check('le serie partono dai pesi dell\'ultima volta', async () => expect(await kg.nth(0).inputValue()).toBe('80'))
  await kg.nth(0).fill('82,5'); await kg.nth(1).fill('85'); await kg.nth(2).fill('85')
  await reps.nth(2).fill('6')
  await p.getByPlaceholder(/fastidio/).fill('Ultima serie dura')
  await shot(p, 'c1_diario')
  await p.getByRole('button', { name: 'Salva allenamento' }).click()
  await check('messaggio "Nuovo record personale: 85 kg"', () => expect(p.getByText(/Nuovo record personale: 85 kg/)).toBeVisible({ timeout: 8000 }))
  await check('l\'esercizio risulta fatto oggi', () => expect(p.locator('.border-success\\/50')).toHaveCount(1))
  // riapro: ci sono le serie di oggi e la nota; il record resta 80 (quello prima di oggi)
  await p.getByText('Panca piana').first().click()
  await check('riaprendo ritrovo serie e nota di oggi', async () => { expect(await p.getByPlaceholder('kg').nth(1).inputValue()).toBe('85'); expect(await p.getByPlaceholder(/fastidio/).inputValue()).toBe('Ultima serie dura') })
  await p.getByPlaceholder('kg').nth(0).fill('2000')
  await p.getByRole('button', { name: 'Salva allenamento' }).click()
  await check('peso assurdo rifiutato con un messaggio chiaro', () => expect(p.getByText(/Controlla i numeri/)).toBeVisible())
  await p.keyboard.press('Escape'); await p.waitForTimeout(400)

  await p.goto(BASE + '/app/allenamento?tab=progressi')
  await check('progressi: record personali con Panca 85 kg', () => expect(p.getByText('Record personali')).toBeVisible())
  await check('progressi: valore 85 kg (prima 80)', () => expect(p.getByText(/prima 80 kg/)).toBeVisible())
  await check('progressi: grafico carichi per esercizio', () => expect(p.getByText('Carichi per esercizio')).toBeVisible())
  // misura nuova
  await p.getByRole('button', { name: 'Misura', exact: true }).click()
  await p.getByLabel(/Peso \(kg\)/).fill('82')
  await p.getByRole('button', { name: 'Salva', exact: true }).click()
  await check('nuova misura: peso 82 e -2 kg dall\'inizio', () => expect(p.getByText(/-2 kg dall'inizio/)).toBeVisible({ timeout: 8000 }))
  // foto
  const file = p.locator('input[type=file]')
  await file.setInputFiles('/tmp/claude-0/e2e/prima.png'); await p.getByText('Foto salvata').first().waitFor({ timeout: 8000 })
  await p.waitForTimeout(500)
  await file.setInputFiles('/tmp/claude-0/e2e/dopo.png'); await p.waitForTimeout(1500)
  await check('due foto caricate', () => expect(p.getByRole('img', { name: /Foto del/ })).toHaveCount(2))
  await check('confronto prima/dopo visibile', () => expect(p.getByText('Prima e dopo')).toBeVisible())
  await check('le immagini si aprono (URL firmato)', async () => { const ok = await p.getByRole('img', { name: /Prima:/ }).evaluate((i) => i.complete && i.naturalWidth > 0); if (!ok) throw new Error('immagine non caricata') })
  await p.getByRole('button', { name: 'Condividi con il trainer' }).first().click()
  await check('condivisione foto con il trainer', () => expect(p.getByText('Ora la vede anche il tuo trainer')).toBeVisible())
  await shot(p, 'c1_progressi')

  await p.goto(BASE + '/app/allenamento?tab=traguardi')
  await check('traguardi: "Primo record" sbloccato', () => expect(p.locator('div.border-gold\\/50', { hasText: 'Primo record' })).toBeVisible())
  await check('traguardi: "Leggenda" ancora da sbloccare', () => expect(p.locator('div.opacity-60', { hasText: 'Leggenda della palestra' })).toBeVisible())
  await shot(p, 'c1_traguardi')

  await p.goto(BASE + '/app/notifiche')
  await check('notifica del record e dei traguardi', async () => { await expect(p.getByText('Nuovo record personale 🏆')).toBeVisible(); await expect(p.getByText(/Nuovo traguardo: Primo record/)).toBeVisible() })

  await p.goto(BASE + '/app/messaggi')
  await check('messaggi: il trainer è in cima con "Il tuo trainer"', () => expect(p.locator('button.card').first()).toContainText('Il tuo trainer'))
  await p.locator('button.card').first().click()
  await p.getByPlaceholder('Scrivi un messaggio…').fill('Ciao Tino, oggi 85 kg di panca!')
  await p.getByRole('button', { name: 'Invia' }).click()
  await p.waitForTimeout(800)
  await check('messaggio inviato', () => expect(p.getByText('Ciao Tino, oggi 85 kg di panca!')).toBeVisible())
  await p.getByText('← Indietro').click()
  await check('lista conversazioni con anteprima "Tu: …"', () => expect(p.getByText(/Tu: Ciao Tino/)).toBeVisible())
  await shot(p, 'c1_messaggi')
  await browser.close()
  process.exit(done())
})()
